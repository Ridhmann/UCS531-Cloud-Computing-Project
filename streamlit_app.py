"""Streamlit front end for the serverless RAG pipeline on AWS.

All work happens in the cloud; this app only calls API Gateway:
  POST /upload-url -> presigned S3 URL (S3 PUT then triggers Textract ingestion)
  POST /query      -> top-k chunks by cosine similarity (Titan embeddings)
  POST /answer     -> answer generated by Bedrock from those chunks
"""

import json
import os

import requests
import streamlit as st

DEFAULT_API_BASE_URL = (
    "https://s35t79fgcl.execute-api.ap-south-1.amazonaws.com/dev"
)

# Documents already ingested by the batch upload in index.ipynb.
KNOWN_DOCUMENTS = {
    "Attention Is All You Need": "bad18322",
    "Deep Residual Learning for Image Recognition": "c3906487",
    "Generative Adversarial Networks": "342a7a1b",
    "BERT: Pre-training of Deep Bidirectional Transformers": "be6d073f",
    "A Survey of Large Language Models": "ac5ca20f",
}

ALL_DOCUMENTS = "All documents"

# API Gateway REST integrations time out at 29 s; leave headroom.
API_TIMEOUT = 35
UPLOAD_TIMEOUT = 120


class ApiError(Exception):
    pass


def get_setting(name, default=None):
    try:
        value = st.secrets.get(name)
    except Exception:
        value = None
    return value or os.environ.get(name) or default


def api_headers():
    # Sent only when the API stage requires a key (see README).
    key = get_setting("API_KEY")
    return {"x-api-key": key} if key else {}


def parse_response(response):
    """Return the JSON payload, unwrapping a Lambda proxy 'body' if present."""
    try:
        data = response.json()
    except ValueError:
        raise ApiError(f"Non-JSON response: {response.text[:300]}")

    if isinstance(data, dict) and "body" in data:
        body = data["body"]
        if isinstance(body, str):
            try:
                body = json.loads(body)
            except ValueError:
                raise ApiError(f"Could not decode body: {body[:300]}")
        data = body

    if not isinstance(data, dict):
        raise ApiError(f"Unexpected response: {str(data)[:300]}")
    return data


def post_json(base_url, path, payload):
    try:
        response = requests.post(
            f"{base_url}/{path}",
            json=payload,
            headers=api_headers(),
            timeout=API_TIMEOUT,
        )
    except requests.Timeout:
        raise ApiError(f"/{path} timed out after {API_TIMEOUT}s.")
    except requests.RequestException as e:
        raise ApiError(f"Could not reach /{path}: {e}")

    if response.status_code == 403 and not api_headers():
        raise ApiError(
            f"/{path} returned 403. If the API now requires a key, "
            "set API_KEY (see README)."
        )
    if response.status_code == 504:
        raise ApiError(
            f"/{path} timed out in API Gateway (29 s limit). Try a single "
            "document instead of all documents."
        )
    if response.status_code != 200:
        raise ApiError(
            f"/{path} failed (HTTP {response.status_code}): "
            f"{response.text[:300]}"
        )

    data = parse_response(response)
    if "error" in data:
        raise ApiError(f"/{path} returned an error: {data['error']}")
    return data


def upload_pdf(base_url, filename, file_bytes):
    data = post_json(base_url, "upload-url", {"filename": filename})
    upload_url = data.get("upload_url")
    doc_id = data.get("document_id")
    if not upload_url or not doc_id:
        raise ApiError(f"Incomplete /upload-url response: {data}")

    try:
        response = requests.put(
            upload_url, data=file_bytes, timeout=UPLOAD_TIMEOUT
        )
    except requests.RequestException as e:
        raise ApiError(f"S3 upload failed: {e}")

    if response.status_code != 200:
        raise ApiError(
            f"S3 upload failed (HTTP {response.status_code}): "
            f"{response.text[:300]}"
        )
    return doc_id


def ask(base_url, question, doc_id, top_k):
    query_data = post_json(
        base_url,
        "query",
        {"question": question, "document_id": doc_id, "top_k": top_k},
    )
    top_chunks = query_data.get("top_chunks") or []
    if not top_chunks:
        return None, []

    answer_data = post_json(
        base_url,
        "answer",
        {"question": question, "top_chunks": top_chunks},
    )
    return (
        answer_data.get("answer", "No answer returned."),
        answer_data.get("sources") or [],
    )


st.set_page_config(page_title="Cloud PDF AI Assistant", page_icon="📄")
st.title("Cloud PDF AI Assistant")
st.write(
    "Ask questions about research papers processed by a serverless RAG "
    "pipeline on AWS (S3, Textract, Lambda, DynamoDB, Bedrock)."
)

if "uploaded_docs" not in st.session_state:
    st.session_state.uploaded_docs = {}

with st.sidebar:
    st.header("Settings")
    api_base_url = st.text_input(
        "API Gateway base URL",
        value=get_setting("API_BASE_URL", DEFAULT_API_BASE_URL),
    ).rstrip("/")
    top_k = st.slider("Chunks to retrieve (top_k)", 1, 10, 5)

    st.header("Upload a new PDF")
    pdf = st.file_uploader("PDF file", type=["pdf"])
    if pdf is not None and st.button("Upload to S3"):
        try:
            with st.spinner("Requesting presigned URL and uploading..."):
                new_id = upload_pdf(api_base_url, pdf.name, pdf.getvalue())
            st.session_state.uploaded_docs[f"{pdf.name} (uploaded)"] = new_id
            st.success(f"Uploaded. Document ID: {new_id}")
            st.info(
                "Ingestion is asynchronous: Textract extraction plus the "
                "5-minute embedding job usually takes 5-10 minutes. "
                "Questions return no results until it finishes."
            )
        except ApiError as e:
            st.error(str(e))

documents = {
    ALL_DOCUMENTS: None,
    **KNOWN_DOCUMENTS,
    **st.session_state.uploaded_docs,
}
choice = st.selectbox("Document", list(documents) + ["Other document ID..."])
if choice == "Other document ID...":
    doc_id = st.text_input("Document ID").strip() or None
else:
    doc_id = documents[choice]

question = st.text_input("Ask a question")

if st.button("Get answer"):
    if not question.strip():
        st.warning("Please enter a question.")
    else:
        try:
            with st.spinner("Retrieving chunks and generating answer..."):
                answer, sources = ask(
                    api_base_url, question.strip(), doc_id, top_k
                )
        except ApiError as e:
            st.error(str(e))
        else:
            if answer is None:
                st.warning(
                    "No relevant chunks found. If you uploaded this "
                    "document recently, ingestion may still be running."
                )
            else:
                st.subheader("Answer")
                st.write(answer)

                if sources:
                    st.subheader("Sources")
                    for i, src in enumerate(sources, 1):
                        score = src.get("similarity_score")
                        score_text = (
                            f"{score:.4f}"
                            if isinstance(score, (int, float))
                            else score
                        )
                        with st.expander(
                            f"{i}. {src.get('filename', 'unknown')} - "
                            f"chunk {src.get('chunk_index', '?')}, "
                            f"score {score_text}"
                        ):
                            st.write(src.get("excerpt", ""))
